export const SYSTEM_MAP: Record<string, SystemDef> = Object.fromEntries(
  SYSTEMS.map((s) => [s.id, s])
);

export function systemsForStage(stage: StageId): SystemDef[] {
  return SYSTEMS.filter((s) => s.stage === stage);
}

export function systemCost(sys: SystemDef, owned: number, costReduction = 0): Partial<Record<string, number>> {
  const mult = Math.pow(sys.costGrowth, owned) * (1 - costReduction);
  const out: Record<string, number> = {};
  for (const [k, v] of Object.entries(sys.baseCost)) {
    out[k] = Math.max(1, Math.ceil((v as number) * mult));
  }
  return out;
}
