// ===========================================================================
// LAYER 3 — DIVINE INVESTMENT MARKET (PORTFOLIOS)
// ===========================================================================
// The L3 Divine Market becomes a dividend investment system tied to your
// background worlds (simulations). Each background world produces Divinity at
// 1% of peakProductionRate/sec; allocating worlds to a portfolio multiplies
// that base output by the portfolio's yield (e.g. +5% for Growth Fund).
//
//   dividendsPerSec = allocatedWorlds × baseYield × peakProductionRate × 0.01
//
// Each portfolio has a "price" that random-walks (50–200) and a crashChance /
// crashLoss that may consume a fraction of allocated worlds per tick. Blood
// Pacts (existing L3 mechanic) become margin calls — Faith can cover a crash
// instead of losing the worlds (handled in the modal/store via the existing
// `faith` pool, see `coverMarginCall` in store.ts).
//
// This module is read-only data — the runtime state (allocations, lock timers,
// prices, lifetime dividends) lives on GameState and is mutated by store
// actions `allocateWorlds`, `deallocateWorlds`, `buyStarFromMarket`, and the
// `tick` portfolio logic.
// ===========================================================================

export type RiskLevel = "zero" | "low" | "medium" | "high" | "extreme";

export interface Portfolio {
  /** Slug id, e.g. "growth". */
  id: string;
  /** Display name, e.g. "Growth Fund". */
  name: string;
  /** Emoji icon shown on the portfolio card. */
  icon: string;
  /** Risk bucket — drives the warning badge shown on the card. */
  riskLevel: RiskLevel;
  /** Per-tick dividend multiplier on base world output (0.05 = +5%). */
  baseYield: number;
  /** Chance per tick that the portfolio "crashes" (loses worlds). 0–1. */
  crashChance: number;
  /** Fraction of allocated worlds lost on a crash (0.10 = −10%). */
  crashLoss: number;
  /** If set, worlds allocated to this portfolio are locked for this many
   *  seconds before they can be deallocated (Stability Bonds = 120s). */
  lockDuration?: number;
  /** Tailwind color token used for accents/badges (e.g. "emerald"). */
  color: string;
  /** Short flavour description shown on the portfolio card. */
  desc: string;
}

