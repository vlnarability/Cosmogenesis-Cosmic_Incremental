/**
 * Compute the dividends-per-second generated by a single portfolio given the
 * current peak production rate. This mirrors the formula used inside the tick
 * so the UI can show a live preview:
 *
 *   dividendsPerSec = allocatedWorlds × baseYield × peakProductionRate × 0.01
 *
 * (`× 0.01` matches the 1%-of-peak-per-world background simulation rule.)
 */
export function portfolioDividendsPerSec(
  portfolio: Portfolio,
  allocatedWorlds: number,
  peakProductionRate: number
): number {
  if (allocatedWorlds <= 0 || peakProductionRate <= 0) return 0;
  return allocatedWorlds * portfolio.baseYield * peakProductionRate * 0.01;
}

/**
 * Sum of all portfolio allocations. Use this to compute the pool of free worlds:
 *   freeWorlds = backgroundSimulations − totalAllocatedWorlds(allocations)
 */
export function totalAllocatedWorlds(
  allocations: Record<string, number>
): number {
  let total = 0;
  for (const p of PORTFOLIOS) {
    total += Math.max(0, Math.floor(allocations[p.id] || 0));
  }
  return total;
}

/**
 * Risk label → human-readable summary for the portfolio card.
 */
export function riskLabel(risk: RiskLevel): string {
  switch (risk) {
    case "zero": return "Zero risk";
    case "low": return "Low risk";
    case "medium": return "Medium risk";
    case "high": return "High risk";
    case "extreme": return "EXTREME risk";
  }
}
